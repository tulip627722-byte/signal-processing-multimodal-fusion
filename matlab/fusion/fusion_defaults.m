function o = fusion_defaults(opts, matlabDir)
%FUSION_DEFAULTS Configuration for static three-modal fusion.
if nargin < 1 || isempty(opts), opts = struct(); end
if nargin < 2 || isempty(matlabDir), matlabDir = fileparts(fileparts(mfilename('fullpath'))); end
projectRoot = fileparts(matlabDir);
d = struct('nDepthFrames', 30, 'depthWindowMs', 1200, 'lidarWindowMs', 1500, ...
    'radarPersistenceRatio', 0.25, 'radarMinFrames', 3, 'radarMaxDopplerMps', 0.25, ...
    'depthRangeM', [0.4 12], 'depthVoxelM', 0.02, 'lidarVoxelM', 0.02, ...
    'radarVoxelM', 0.08, 'fovMinDepthM', 0.25, 'maxNearestDistanceM', 0.50, ...
    'radarClusterEpsM', 0.38, 'radarClusterMinPoints', 2, ...
    'radarAssociationRangeToleranceM', 0.35, 'radarAssociationAzimuthDeg', 5.0, ...
    'radarAssociationLocalRadiusM', 0.30, 'displayProfile', 'standard', ...
    'boardPlaneRansacThresholdM', 0.06, ...
    'boardWidthM', 0.35, 'boardHeightM', 0.35, 'boardClusterNormalToleranceM', 0.25, ...
    'knownBoardCorrespondenceFile', fullfile(projectRoot, 'docs', 'extrinsics', 'lidar-radar', 'lidar_radar_correspondences.csv'), ...
    'guidedRadarRangeCandidateFile', fullfile(projectRoot, 'docs', 'extrinsics', 'radar-guided-board', 'guided_radar_board_range_candidate.json'), ...
    'maxDiagnosticPoints', 20000, 'maxFusionPointsPerSensor', 60000, ...
    'resultsDir', fullfile(projectRoot, 'results', 'takes'), ...
    'cameraExtrinsicsFile', fullfile(matlabDir, 'radar_camera_extrinsics.json'), ...
    'lidarExtrinsicsFile', fullfile(projectRoot, 'docs', 'extrinsics', 'lidar-radar', ...
    'lidar_radar_extrinsics_candidate.json'), ...
    'outputDir', fullfile(projectRoot, 'results', 'static_fusion'), ...
    'runRefinement', false, 'refinementIterations', 12, 'savePly', true, ...
    'randomSeed', 20261123);
fields = fieldnames(d);
for index = 1:numel(fields)
    if ~isfield(opts, fields{index}), opts.(fields{index}) = d.(fields{index}); end
end
o = opts;
end
