using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;

namespace Acquire
{
    internal struct CloudPoint
    {
        public double X, Y, Z;
        public int U, V;
        public double DepthMeters;
    }

    /// <summary>
    /// 由 16-bit 深度图生成点云。Astra Pro 不输出点云，只有针孔模型：
    ///
    ///   Z = depth(u,v) * depthScale
    ///   X = (u - cx) * Z / fx
    ///   Y = (v - cy) * Z / fy
    ///
    /// 所以采集时永远存“原始深度图 + 内参”，点云是按需算出来的派生数据。
    /// 无效深度（0）跳过；典型 640x480 + stride 4 每帧约 1.9 万点。
    ///
    /// 坐标系：
    ///   相机坐标 X 右 / Y 下 / Z 前（深度沿光轴向前）
    ///   雷达坐标 X 右 / Y 前 / Z 上
    ///   转换：X_radar = X_cam，Y_radar = Z_cam，Z_radar = -Y_cam
    /// 这只是把两套坐标轴对齐，**不含**雷达与相机之间的平移/旋转（外参还没标定）。
    /// </summary>
    internal static class DepthCloud
    {
        public const int DefaultStride = 4;

        [StructLayout(LayoutKind.Explicit)]
        private struct FloatBits
        {
            [FieldOffset(0)] public float Value;
            [FieldOffset(0)] public uint Bits;
        }

        /// <summary>
        /// 按 stride 在像素网格上取样（u = 0, stride, 2*stride…），深度为 0 的像素跳过。
        /// sampled 是网格位置总数，valid 是有深度的位置数，points.Count 应该等于 valid。
        /// </summary>
        public static List<CloudPoint> Build(ushort[] depth, int width, int height, DepthIntrinsics intrinsics,
                                             int stride, bool radarFrame, out int sampled, out int valid)
        {
            if (depth == null) throw new ArgumentNullException("depth");
            if (intrinsics == null) throw new ArgumentNullException("intrinsics");
            if (width <= 0 || height <= 0) throw new ArgumentException("图像尺寸非法");
            if (depth.Length < width * height) throw new ArgumentException("深度缓冲小于图像尺寸");
            if (!intrinsics.Valid) throw new ArgumentException("内参不合法：" + intrinsics.Describe());
            if (width != intrinsics.Width || height != intrinsics.Height)
                throw new ArgumentException("深度图尺寸 " + width + "x" + height +
                                            " 与内参记录的分辨率 " + intrinsics.Width + "x" + intrinsics.Height +
                                            " 不一致，无法直接套用针孔模型");
            if (stride < 1) stride = 1;

            int capacity = ((width + stride - 1) / stride) * ((height + stride - 1) / stride);
            List<CloudPoint> points = new List<CloudPoint>(capacity);
            sampled = 0;
            valid = 0;

            for (int v = 0; v < height; v += stride)
            {
                int row = v * width;
                for (int u = 0; u < width; u += stride)
                {
                    sampled++;
                    ushort raw = depth[row + u];
                    if (raw == 0) continue;
                    valid++;

                    double z = raw * intrinsics.DepthScale;
                    double x = (u - intrinsics.Cx) * z / intrinsics.Fx;
                    double y = (v - intrinsics.Cy) * z / intrinsics.Fy;

                    CloudPoint point = new CloudPoint();
                    point.U = u;
                    point.V = v;
                    point.DepthMeters = z;
                    if (radarFrame)
                    {
                        point.X = x;
                        point.Y = z;
                        point.Z = -y;
                    }
                    else
                    {
                        point.X = x;
                        point.Y = y;
                        point.Z = z;
                    }
                    points.Add(point);
                }
            }
            return points;
        }

        /// <summary>相机坐标 → 雷达坐标：X_radar = X_cam，Y_radar = Z_cam，Z_radar = -Y_cam。</summary>
        public static void ToRadarFrame(List<CloudPoint> points)
        {
            if (points == null) return;
            for (int i = 0; i < points.Count; i++)
            {
                CloudPoint p = points[i];
                double y = p.Y;
                p.Y = p.Z;
                p.Z = -y;
                points[i] = p;
            }
        }

        public static string BuildPlyHeader(int count, string frame, string comment)
        {
            StringBuilder sb = new StringBuilder(256);
            sb.Append("ply\n");
            sb.Append("format binary_little_endian 1.0\n");
            sb.Append("comment Generated by Acquire.exe\n");
            sb.Append("comment frame ").Append(frame).Append('\n');
            if (!string.IsNullOrEmpty(comment)) sb.Append("comment ").Append(comment.Replace('\r', ' ').Replace('\n', ' ')).Append('\n');
            sb.Append("element vertex ").Append(count.ToString(CultureInfo.InvariantCulture)).Append('\n');
            sb.Append("property float x\n");
            sb.Append("property float y\n");
            sb.Append("property float z\n");
            sb.Append("end_header\n");
            return sb.ToString();
        }

        /// <summary>写 binary_little_endian PLY（12 字节/点，float32 xyz）。</summary>
        public static void WritePly(string path, List<CloudPoint> points, string frame, string comment)
        {
            if (points == null) throw new ArgumentNullException("points");
            byte[] header = Encoding.ASCII.GetBytes(BuildPlyHeader(points.Count, frame, comment));
            using (FileStream stream = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.Read, 1 << 16))
            {
                stream.Write(header, 0, header.Length);
                byte[] vertex = new byte[12];
                for (int i = 0; i < points.Count; i++)
                {
                    PutFloat(vertex, 0, points[i].X);
                    PutFloat(vertex, 4, points[i].Y);
                    PutFloat(vertex, 8, points[i].Z);
                    stream.Write(vertex, 0, vertex.Length);
                }
            }
        }

        public static void WriteCsv(string path, List<CloudPoint> points)
        {
            if (points == null) throw new ArgumentNullException("points");
            using (StreamWriter writer = new StreamWriter(path, false, new UTF8Encoding(false), 1 << 16))
            {
                writer.Write("X,Y,Z\r\n");
                for (int i = 0; i < points.Count; i++)
                {
                    writer.Write(points[i].X.ToString("0.######", CultureInfo.InvariantCulture));
                    writer.Write(',');
                    writer.Write(points[i].Y.ToString("0.######", CultureInfo.InvariantCulture));
                    writer.Write(',');
                    writer.Write(points[i].Z.ToString("0.######", CultureInfo.InvariantCulture));
                    writer.Write("\r\n");
                }
            }
        }

        /// <summary>读 PLY 头，拿顶点数并核对文件长度（防止写盘被截断）。</summary>
        public static int ReadPlyVertexCount(string path, out string error, out string format)
        {
            error = null;
            format = null;
            using (FileStream stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read))
            {
                List<byte> header = new List<byte>(1024);
                bool headerEnd = false;
                int b;
                while ((b = stream.ReadByte()) >= 0)
                {
                    header.Add((byte)b);
                    if (b == '\n')
                    {
                        int n = header.Count;
                        int start = n - 1;
                        while (start > 0 && header[start - 1] != '\n') start--;
                        int end = n - 1;
                        if (end > start && header[end - 1] == '\r') end--;
                        string line = Encoding.ASCII.GetString(header.GetRange(start, end - start).ToArray());
                        if (line == "end_header")
                        {
                            headerEnd = true;
                            break;
                        }
                    }
                    if (header.Count > 1 << 16)
                    {
                        error = "PLY 头超过 64 KB，不是有效文件";
                        return -1;
                    }
                }

                string text = Encoding.ASCII.GetString(header.ToArray());
                if (!text.StartsWith("ply", StringComparison.Ordinal))
                {
                    error = "缺少 ply 魔数";
                    return -1;
                }
                if (!headerEnd)
                {
                    error = "找不到 end_header（文件可能被截断）";
                    return -1;
                }

                long headerBytes = header.Count;
                int count = -1;
                bool binary = false;
                using (StringReader reader = new StringReader(text))
                {
                    string line;
                    while ((line = reader.ReadLine()) != null)
                    {
                        string trimmed = line.Trim();
                        if (trimmed.StartsWith("format ", StringComparison.Ordinal))
                        {
                            format = trimmed.Substring(7).Trim();
                            binary = format.StartsWith("binary_little_endian", StringComparison.Ordinal);
                        }
                        else if (trimmed.StartsWith("element vertex ", StringComparison.Ordinal))
                        {
                            int parsed;
                            if (int.TryParse(trimmed.Substring(15).Trim(), NumberStyles.Integer,
                                    CultureInfo.InvariantCulture, out parsed)) count = parsed;
                        }
                    }
                }
                if (count < 0)
                {
                    error = "没有 element vertex 行";
                    return -1;
                }

                long fileLength = stream.Length;
                if (binary)
                {
                    long expected = headerBytes + (long)count * 12;
                    if (fileLength != expected)
                    {
                        error = "文件长度 " + fileLength + " 与期望 " + expected + " 不符（" + count + " 点 × 12 字节）";
                        return -1;
                    }
                }
                else
                {
                    long dataLines = 0;
                    using (StreamReader reader = new StreamReader(path, Encoding.ASCII))
                    {
                        string line;
                        bool inData = false;
                        while ((line = reader.ReadLine()) != null)
                        {
                            if (!inData)
                            {
                                if (line.Trim() == "end_header") inData = true;
                                continue;
                            }
                            if (line.Trim().Length > 0) dataLines++;
                        }
                    }
                    if (dataLines != count)
                    {
                        error = "ASCII PLY 数据行数 " + dataLines + " 与声明 " + count + " 不符";
                        return -1;
                    }
                }
                return count;
            }
        }

        private static void PutFloat(byte[] buffer, int offset, double value)
        {
            FloatBits bits = new FloatBits();
            bits.Value = (float)value;
            uint raw = bits.Bits;
            buffer[offset] = (byte)(raw & 0xFF);
            buffer[offset + 1] = (byte)((raw >> 8) & 0xFF);
            buffer[offset + 2] = (byte)((raw >> 16) & 0xFF);
            buffer[offset + 3] = (byte)((raw >> 24) & 0xFF);
        }

        public static string DescribeExtent(List<CloudPoint> points)
        {
            if (points == null || points.Count == 0) return "空点云";
            double minX = double.MaxValue, maxX = double.MinValue;
            double minY = double.MaxValue, maxY = double.MinValue;
            double minZ = double.MaxValue, maxZ = double.MinValue;
            for (int i = 0; i < points.Count; i++)
            {
                CloudPoint p = points[i];
                if (p.X < minX) minX = p.X;
                if (p.X > maxX) maxX = p.X;
                if (p.Y < minY) minY = p.Y;
                if (p.Y > maxY) maxY = p.Y;
                if (p.Z < minZ) minZ = p.Z;
                if (p.Z > maxZ) maxZ = p.Z;
            }
            return "X " + minX.ToString("0.000", CultureInfo.InvariantCulture) + "~" + maxX.ToString("0.000", CultureInfo.InvariantCulture) +
                   " / Y " + minY.ToString("0.000", CultureInfo.InvariantCulture) + "~" + maxY.ToString("0.000", CultureInfo.InvariantCulture) +
                   " / Z " + minZ.ToString("0.000", CultureInfo.InvariantCulture) + "~" + maxZ.ToString("0.000", CultureInfo.InvariantCulture) + " m";
        }
    }
